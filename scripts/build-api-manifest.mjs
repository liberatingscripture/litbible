/**
 * build-api-manifest.mjs
 *
 * Generates /api/manifest.json and copies content files to /api/data/
 * so the iOS and Android apps can check for updates and download changed files.
 *
 * Runs automatically as part of `npm run build`.
 */

import { promises as fs } from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDir, '..');
const dataDir = path.join(projectRoot, 'src', 'data');
const publicImagesDir = path.join(projectRoot, 'public', 'images');
const outputBase = path.join(projectRoot, 'public', 'api');
const outputData = path.join(outputBase, 'data');

// Matches src="/images/<filename>" in intro markdown/HTML. The leading slash is
// site-root-relative; the iOS app rewrites these to bare filenames at render
// time and resolves from a local image directory, so we expose them in the
// manifest under "images/<filename>".
const IMAGE_REF_RE = /\/images\/([A-Za-z0-9._-]+)/g;

function hashBuffer(buf) {
  return crypto.createHash('sha256').update(buf).digest('hex');
}

/**
 * Collect all content files that should be served to the apps.
 * Returns an array of { relativePath, absolutePath } objects.
 */
async function collectContentFiles() {
  const files = [];

  // chapters/*.json
  const chaptersDir = path.join(dataDir, 'chapters');
  for (const name of await fs.readdir(chaptersDir)) {
    if (name.endsWith('.json')) {
      files.push({
        relativePath: `chapters/${name}`,
        absolutePath: path.join(chaptersDir, name),
      });
    }
  }

  // intros/*.md — also collect any /images/<filename> references found inside
  const referencedImages = new Set();
  const introsDir = path.join(dataDir, 'intros');
  try {
    for (const name of await fs.readdir(introsDir)) {
      if (name.endsWith('.md')) {
        const abs = path.join(introsDir, name);
        files.push({
          relativePath: `intros/${name}`,
          absolutePath: abs,
        });
        const text = await fs.readFile(abs, 'utf8');
        for (const match of text.matchAll(IMAGE_REF_RE)) {
          referencedImages.add(match[1]);
        }
      }
    }
  } catch {
    // intros directory may not exist yet
  }

  // images/<filename> — every image referenced from an intro file
  for (const filename of referencedImages) {
    const abs = path.join(publicImagesDir, filename);
    try {
      await fs.access(abs);
      files.push({
        relativePath: `images/${filename}`,
        absolutePath: abs,
      });
    } catch {
      console.warn(`⚠️  intro references /images/${filename} but file not found in public/images/`);
    }
  }

  // Top-level data files. `required: true` files MUST be present — the apps
  // depend on them, so a missing one is a build error rather than a silent
  // skip. `sources` lists candidate paths in priority order (the first that
  // exists wins); this lets `topics.json` and `glossary.json` fall back to
  // generated files since neither has a hand-authored source.
  //
  // `glossary.json` was declared OPTIONAL from 2026-03 until 2026-08 with a
  // source that never existed, so the build skipped it silently and the API
  // carried no glossary data for five months while both apps sat on divergent
  // bundled copies. It is required now precisely so that cannot recur: the
  // failure mode of an optional sync file is silence.
  const topLevelFiles = [
    {
      relativePath: 'glossary.json',
      required: true,
      sources: [
        path.join(dataDir, 'glossary.json'),
        path.join(projectRoot, 'public', 'glossary.json'),
      ],
    },
    { relativePath: 'release-notes.json', sources: [path.join(dataDir, 'release-notes.json')] },
    {
      relativePath: 'topics.json',
      required: true,
      sources: [
        path.join(dataDir, 'topics.json'),
        path.join(projectRoot, 'public', 'topics-index.json'),
      ],
    },
    {
      relativePath: 'translation-commitments.json',
      required: true,
      sources: [path.join(dataDir, 'translation-commitments.json')],
    },
  ];

  for (const { relativePath, sources, required } of topLevelFiles) {
    let resolved = null;
    for (const candidate of sources) {
      try {
        await fs.access(candidate);
        resolved = candidate;
        break;
      } catch {
        // try next candidate
      }
    }
    if (resolved) {
      files.push({ relativePath, absolutePath: resolved });
    } else if (required) {
      throw new Error(
        `Required sync file "${relativePath}" not found. Checked: ${sources.join(', ')}. ` +
          `(topics.json is generated by build:topics and glossary.json by build:glossary — ` +
          `ensure both run before build:manifest.)`,
      );
    }
    // optional + missing → skip silently
  }

  return files;
}

async function main() {
  const files = await collectContentFiles();
  const now = new Date();

  // Ensure output directories exist
  await fs.mkdir(path.join(outputData, 'chapters'), { recursive: true });
  await fs.mkdir(path.join(outputData, 'intros'), { recursive: true });

  const fileHashes = {};
  for (const { relativePath, absolutePath } of files) {
    const content = await fs.readFile(absolutePath);
    fileHashes[relativePath] = hashBuffer(content);

    const dest = path.join(outputData, relativePath);
    await fs.mkdir(path.dirname(dest), { recursive: true });
    await fs.writeFile(dest, content);
  }

  // Sort keys so the manifest is byte-stable across rebuilds (deterministic
  // diffs) and the content hash below is order-independent.
  const sortedFiles = {};
  for (const key of Object.keys(fileHashes).sort()) {
    sortedFiles[key] = fileHashes[key];
  }

  // The version string is the contract the mobile apps key on: they only pull
  // when it changes (a Tier-1 version.json poll gates everything). So it MUST
  // change whenever ANY synced file changes — and stay stable when nothing
  // does. We derive it from the content hashes themselves: a date prefix for
  // human readability plus a short digest of every file hash. Two publishes on
  // the same day therefore still produce distinct versions.
  const contentHash = crypto
    .createHash('sha256')
    .update(Object.entries(sortedFiles).map(([k, v]) => `${k}:${v}`).join('\n'))
    .digest('hex')
    .slice(0, 8);
  const version = `v${now.toISOString().slice(0, 10).replace(/-/g, '')}.${contentHash}`;
  const chapterCount = Object.keys(sortedFiles).filter((k) => k.startsWith('chapters/')).length;

  const manifest = {
    version,
    generatedAt: now.toISOString(),
    files: sortedFiles,
  };
  await fs.writeFile(
    path.join(outputBase, 'manifest.json'),
    JSON.stringify(manifest, null, 2),
  );

  // version.json is the lightweight gate the apps poll first. Written here (not
  // in build-api-json) so its version is derived from the full synced content
  // set and is guaranteed to match manifest.json / content.json.
  const versionPayload = {
    version,
    updatedAt: now.toISOString(),
    chapterCount,
    contentHash,
  };
  await fs.writeFile(
    path.join(outputBase, 'version.json'),
    JSON.stringify(versionPayload),
    'utf8',
  );

  console.log(
    `✅ public/api/manifest.json written — ${Object.keys(sortedFiles).length} files hashed (version ${version})`,
  );
  console.log(`✅ public/api/version.json written — version: ${version}`);
  console.log(
    `✅ public/api/data/ populated — files ready for app sync`,
  );
}

main().catch((error) => {
  console.error('❌ build-api-manifest failed');
  console.error(error?.stack ?? error);
  process.exit(1);
});
