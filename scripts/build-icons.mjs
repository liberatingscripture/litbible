#!/usr/bin/env node
// Featherboa's icon set ("Controls," "Icons"; SITE-FEATHERBOA-BUILD.md,
// question 10): Lucide's drawings, under the ISC license, on a 24-pixel grid
// with round ends, which src/lib/icons.mjs sets at a 1.5-pixel stroke. This
// reads each drawing from the lucide-static package and writes
// src/lib/icons.mjs, which .astro files and client scripts both import.
// Run by hand (`npm run build:icons`) when the list below changes; it is not
// part of the build. The colophon credits Lucide.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const pkgDir = dirname(require.resolve("lucide-static/package.json"));
const version = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8")).version;

// The record's name for each icon, and Lucide's drawing for it. The first
// sixteen are the set "Icons" draws; the rest are the ones the build needs
// where a typed glyph stood in (▾, ›, the trash) or the header's menu.
const SET = [
  ["read", "book-open"],
  ["notebook", "notebook"],
  ["sheet", "file-text"],
  ["collection", "library"],
  ["highlight", "highlighter"],
  ["note", "sticky-note"],
  ["bookmark", "bookmark"],
  ["copy", "copy"],
  ["share", "share"],
  ["print", "printer"],
  ["layout", "columns-2"],
  ["new", "plus"],
  ["search", "search"],
  ["close", "x"],
  ["back", "chevron-left"],
  ["more", "ellipsis"],
  ["forward", "chevron-right"],
  ["down", "chevron-down"],
  ["up", "chevron-up"],
  ["trash", "trash-2"],
  ["check", "check"],
  ["menu", "menu"],
];

function drawing(file) {
  const svg = readFileSync(join(pkgDir, "icons", `${file}.svg`), "utf8");
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  return inner
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean)
    .join("")
    .replace(/\s*\/>/g, "/>");
}

const entries = SET.map(([name, file]) => `  ${JSON.stringify(name)}: ${JSON.stringify(drawing(file))},`).join("\n");
const sources = SET.map(([name, file]) => `${name} ${file}`).join(", ");

const out = `// GENERATED by scripts/build-icons.mjs from lucide-static ${version} (ISC
// license, https://lucide.dev): don't edit by hand. Change the list there and
// run \`npm run build:icons\`.
//
// Featherboa's one icon set ("Controls," "Icons"): drawn on a 24-pixel grid
// with round ends, at a 1.5-pixel stroke, sized to sit beside its word. An
// icon stands alone only if it is one of the five everyone knows (search,
// close, back, forward, and more), and then the control carries a name for
// screen readers; every other icon keeps its word. Typed glyphs (× ‹ › ▾) no
// longer stand in for icons. Both .astro files (src/components/Icon.astro)
// and client scripts import this module.
//
// Lucide's drawing behind each name: ${sources}.

/** The drawing inside each icon's 24-pixel box, by name. */
export const ICONS = Object.freeze({
${entries}
});

/** The five icons that may stand alone on a control ("Icons"). */
export const STANDALONE = Object.freeze(["search", "close", "back", "forward", "more"]);

/** Whether an icon may stand alone, without its word beside it. */
export const mayStandAlone = (name) => STANDALONE.includes(name);

/**
 * An icon as SVG markup. It is decorative: the control's word, or its
 * aria-label when the icon stands alone, names it. data-icon says which
 * icon it is, for the check that an icon alone is one of the five.
 * @param {string} name one of ICONS' names
 * @param {{ size?: number, className?: string }} [opts]
 */
export function icon(name, { size = 20, className = "icon" } = {}) {
  const body = ICONS[name];
  if (body === undefined) throw new Error(\`no icon named "\${name}"\`);
  return (
    \`<svg class="\${className}" data-icon="\${name}" viewBox="0 0 24 24" width="\${size}" height="\${size}" \` +
    \`fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" \` +
    \`stroke-linejoin="round" aria-hidden="true" focusable="false">\${body}</svg>\`
  );
}

/**
 * The same icon as an element, for scripts that build their controls.
 * @param {string} name
 * @param {{ size?: number, className?: string }} [opts]
 * @returns {SVGElement}
 */
export function iconNode(name, opts) {
  const t = document.createElement("template");
  t.innerHTML = icon(name, opts);
  return /** @type {SVGElement} */ (t.content.firstElementChild);
}
`;

writeFileSync(join(root, "src/lib/icons.mjs"), out);
console.log(`src/lib/icons.mjs: ${SET.length} icons from lucide-static ${version}`);
